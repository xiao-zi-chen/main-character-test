import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { regularRoles as roles } from '../src/data/roles.js';
import { dimensions, questions } from '../src/data/questions.js';
import { SCALE_MAX } from '../src/data/answer-scale.js';
import { SAMPLE_MODELS, sampleScores, seededRandom } from './lib/role-samples.mjs';

// Offline calibration only. The browser uses the resulting fixed offsets;
// answers, historical traffic and randomness never alter them at runtime.
const settings = { seed: 20261029, samples: 50000, iterations: 300, anchorMargin: .15 };
const matchingVersion = 'balanced-2026-10-29-v1';
const count = roles.length;
const random = seededRandom(settings.seed);
const distances = new Float64Array(settings.samples * count);
function distance(values, role) {
  return values.reduce((sum, value, i) => sum + role.weights[i] * ((value - role.profile[i]) / 100) ** 2, 0)
    / role.weights.reduce((sum, weight) => sum + weight, 0);
}
for (let sample = 0; sample < settings.samples; sample++) {
  const values = sampleScores(random, SAMPLE_MODELS[sample % SAMPLE_MODELS.length]).map(score => score.value);
  roles.forEach((role, index) => { distances[sample * count + index] = distance(values, role); });
}

// Keep each character's own profile and its answer-scale approximations in
// that character's region. At least 15% of the original winning margin stays.
const limits = roles.map((role, i) => {
  const anchors = [
    role.profile,
    role.profile.map(value => Math.round(Math.round(value * SCALE_MAX / 100) / SCALE_MAX * 100)),
    role.profile.map(value => Math.round(Math.round(value * SCALE_MAX * 2 / 100) / (SCALE_MAX * 2) * 100)),
    role.profile.map((value, d) => {
      const items = questions.filter(question => question.dimension === dimensions[d].id).length;
      return Math.round(Math.round(value * items / 100) / items * 100);
    }),
  ];
  return roles.map((other, j) => {
    if (i === j) return 0;
    const margin = Math.min(...anchors.map(values => distance(values, other) - distance(values, role)));
    assert.ok(margin > 0, `${role.id} profile is not uniquely reachable; review the catalog before recalibration`);
    return margin * (1 - settings.anchorMargin);
  });
});
const offsets = new Float64Array(count);
for (let iteration = 0; iteration < settings.iterations; iteration++) {
  const wins = new Int32Array(count);
  for (let sample = 0; sample < settings.samples; sample++) {
    let winner = 0, best = Infinity;
    for (let role = 0; role < count; role++) {
      const value = distances[sample * count + role] + offsets[role];
      if (value < best) { best = value; winner = role; }
    }
    wins[winner]++;
  }
  const rate = .08 / (1 + iteration / 70);
  for (let role = 0; role < count; role++) offsets[role] += rate * (wins[role] / settings.samples - 1 / count);
  for (let pass = 0; pass < 10; pass++) {
    for (let i = 0; i < count; i++) for (let j = 0; j < count; j++) {
      const excess = offsets[i] - offsets[j] - limits[i][j];
      if (excess > 0) { offsets[i] -= excess / 2; offsets[j] += excess / 2; }
    }
  }
}
for (let i = 0; i < count; i++) for (let j = 0; j < count; j++) {
  assert.ok(offsets[i] - offsets[j] <= limits[i][j] + 1e-10, 'Anchor constraint did not converge');
}
const basis = {
  settings, models: SAMPLE_MODELS, dimensions: dimensions.map(dimension => dimension.id),
  profiles: roles.map(role => ({ id: role.id, profile: role.profile, weights: role.weights })),
};
const output = `// Generated by node scripts/calibrate_roles.mjs. Recalibrate after changing role profiles.\n`
  + `// Synthetic calibration reduces concentration; it does not promise equal real-world frequencies.\n`
  + `export const MATCHING_VERSION = '${matchingVersion}';\n`
  + `export const ROLE_DISTANCE_OFFSETS = Object.freeze({\n`
  + roles.map((role, i) => `  '${role.id}': ${Number(offsets[i].toFixed(12))},`).join('\n')
  + `\n});\n\n// Reproducibility metadata, excluded from the browser bundle when unused.\n`
  + `export const CALIBRATION_BASIS = ${JSON.stringify(basis, null, 2)};\n`;
await writeFile(new URL('../src/data/role-calibration.js', import.meta.url), output);
console.log(`Calibrated ${count} roles using ${settings.samples} synthetic samples; own-profile constraints passed.`);
